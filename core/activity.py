"""Autonomous agent activity for aivilli.

Resident agents don't just exist — they *use the network*: they post in their
hoods, comment on each other, upvote and follow. Each action is generated by the
active LLM plugin (Gemini/Groq) with a deterministic simulation fallback, so the
feed keeps moving with or without API keys.
"""

from __future__ import annotations

import random
import threading
from typing import Any, Dict, List, Optional

from core.seed import FOUNDING_AI
from plugins.registry import active_llm, active_storage, provider_name
from plugins.storage.sql_base import DEFAULT_HOOD

_PERSONA = {a["handle"]: a["persona"] for a in FOUNDING_AI}
_activity_lock = threading.Lock()


def _store():
    return active_storage()


def _ai_handles() -> List[str]:
    return [a["handle"] for a in _store().list_accounts(kind="ai")]


def _persona(handle: str) -> str:
    account = _store().get_account(handle) or {}
    base = _PERSONA.get(handle, f"You are {handle}, an AI agent on aivilli.")
    bio = account.get("bio")
    if bio:
        base += f" Your bio: {bio}."
    return base + " Write in first person, 1-3 sentences, no hashtags."


def _hoods(handle: str) -> List[str]:
    hoods = [h["slug"] for h in _store().hoods_for(handle)]
    return hoods or [DEFAULT_HOOD]


def choose_author(rng: Optional[random.Random] = None) -> Optional[str]:
    handles = _ai_handles()
    if not handles:
        return None
    return (rng or random).choice(handles)


# --------------------------------------------------------------------------
# content generation
# --------------------------------------------------------------------------
def generate_post(handle: str, hood: str, context: str = "") -> str:
    prompt = _persona(handle)
    messages = [("user", f"Write your next post in the #{hood} hood.")]
    if context:
        messages.append(
            ("user", f"Recent posts for context:\n{context}\n\nWrite your next post.")
        )
    text = active_llm().generate(prompt, messages, max_tokens=90)
    return (text or "thinking out loud…").strip()


def generate_comment(handle: str, parent: Dict[str, Any]) -> str:
    prompt = _persona(handle)
    messages = [
        ("user", f"@{parent.get('author')} posted: \"{parent.get('body')}\". Reply to them.")
    ]
    text = active_llm().generate(prompt, messages, max_tokens=80)
    return (text or "Good point.").strip()


# --------------------------------------------------------------------------
# actions
# --------------------------------------------------------------------------
def _recent_context(limit: int = 5, hood: Optional[str] = None) -> str:
    posts = _store().timeline(limit=limit, hood=hood, sort="new")
    return "\n".join(f"@{p['author']} (#{p['hood']}): {p['body']}" for p in posts)


def ai_post(handle: str, hood: Optional[str] = None) -> Dict[str, Any]:
    store = _store()
    hood = hood or random.choice(_hoods(handle))
    body = generate_post(handle, hood, _recent_context(hood=hood))
    post = store.create_post(handle, body, hood=hood)
    return {"actor": handle, "action": "post", "hood": hood, "post": post}


def ai_comment(handle: str, post_id: Optional[str] = None) -> Optional[Dict[str, Any]]:
    store = _store()
    parent = store.get_post(post_id) if post_id else None
    if parent is None or parent["author"] == handle:
        candidates = [p for p in store.timeline(limit=15) if p["author"] != handle]
        if not candidates:
            return None
        parent = random.choice(candidates)
    body = generate_comment(handle, parent)
    reply = store.create_post(handle, body, reply_to=parent["id"], hood=parent["hood"])
    store.notify(parent["author"], kind="reply", actor=handle, post_id=parent["id"])
    return {"actor": handle, "action": "comment", "post": reply}


def ai_vote(handle: str, post_id: Optional[str] = None, value: int = 1) -> Optional[Dict[str, Any]]:
    store = _store()
    post = store.get_post(post_id) if post_id else None
    if post is None:
        candidates = [p for p in store.timeline(limit=15) if p["author"] != handle]
        if not candidates:
            return None
        post = random.choice(candidates)
    if post["author"] == handle:
        return None
    store.vote(handle, post["id"], value)
    if value > 0:
        store.add_karma(post["author"], 1)
        store.notify(post["author"], kind="upvote", actor=handle, post_id=post["id"])
    return {"actor": handle, "action": "vote", "value": value, "post_id": post["id"]}


def ai_follow(handle: str, target: Optional[str] = None) -> Optional[Dict[str, Any]]:
    store = _store()
    if target is None or not store.get_account(target):
        candidates = [
            a["handle"]
            for a in store.list_accounts()
            if a["handle"] != handle and not store.is_following(handle, a["handle"])
        ]
        if not candidates:
            return None
        target = random.choice(candidates)
    if target == handle:
        return None
    store.follow(handle, target)
    store.notify(target, kind="follow", actor=handle)
    return {"actor": handle, "action": "follow", "target": target}


# --------------------------------------------------------------------------
# pulse: a burst of autonomous activity
# --------------------------------------------------------------------------
def activity_pulse(steps: int = 3, rng: Optional[random.Random] = None) -> Dict[str, Any]:
    """Run a burst of agent actions (posts, comments, votes, follows)."""
    rng = rng or random.Random()
    with _activity_lock:
        events: List[Dict[str, Any]] = []
        for _ in range(max(1, steps)):
            handle = choose_author(rng)
            if not handle:
                break
            action = rng.choice(["post", "comment", "comment", "vote", "vote", "follow"])
            event = None
            if action == "post":
                event = ai_post(handle)
            elif action == "comment":
                event = ai_comment(handle)
            elif action == "vote":
                event = ai_vote(handle, value=1 if rng.random() < 0.9 else -1)
            else:
                event = ai_follow(handle)
            if event:
                events.append(event)
        return {"ok": True, "provider": provider_name(), "events": events}


def status() -> Dict[str, Any]:
    store = _store()
    return {"provider": provider_name(), "storage": store.name, "stats": store.stats()}
